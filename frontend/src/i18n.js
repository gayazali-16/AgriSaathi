const dictionaries = { en, hi, te };

export function translate(language, key) {
  return dictionaries[language]?.[key] ?? en[key] ?? key;
}

export function statusLabel(language, status) {
  const key = `status_${status}`;
  return en[key] ? translate(language, key) : String(status || '').replaceAll('_', ' ');
}

export function cropLabel(language, crop) {
  const key = { Rice: 'cropRice', Maize: 'cropMaize' }[crop];
  return key ? translate(language, key) : crop;
}

export function seasonLabel(language, season) {
  const key = { Kharif: 'seasonKharif', Rabi: 'seasonRabi', Zaid: 'seasonZaid' }[season];
  return key ? translate(language, key) : season;
}

export function fieldStageLabel(language, stage) {
  const key = { Vegetative: 'stageVegetative', Seedling: 'stageSeedling' }[stage];
  return key ? translate(language, key) : stage;
}

export function fieldScopeLabel(language, scope) {
  if (scope === 'District only; sample field profile') return translate(language, 'fieldScopeDistrictOnly');
  return scope;
}

export function topicLabel(language, topic) {
  const key = {
    water_management: 'topicWater',
    nutrient_management: 'topicFertilizer',
    crop_rotation: 'topicRotation',
    intercropping: 'topicIntercropping',
    integrated_pest_management: 'topicPest',
  }[topic];
  return key ? translate(language, key) : translate(language, 'topicDefault');
}

export function basisLabel(language, basis) {
  const key = {
    research: 'basisResearch',
    mixed: 'basisMixed',
    general: 'basisGeneral',
    unavailable: 'basisUnavailable',
  }[basis] || 'basisGeneral';
  return translate(language, key);
}

export function localizeError(language, error) {
  const status = Number(error?.status || 0);
  const key = status === 0 ? 'apiErrorNetwork'
    : status === 401 || status === 403 ? 'apiErrorDenied'
      : status === 404 ? 'apiErrorNotFound'
      : status === 409 ? 'apiErrorConflict'
        : status === 410 ? 'apiErrorUseContactForm'
          : status === 413 ? 'apiErrorImageLarge'
            : status === 415 ? 'apiErrorImageType'
              : status === 422 ? 'apiErrorInput'
                : status >= 500 ? 'apiErrorServer' : 'apiErrorGeneric';
  return translate(language, key);
}

export function localeTag(language) {
  return ({ en: 'en-IN', hi: 'hi-IN', te: 'te-IN' })[language] || 'en-IN';
}
